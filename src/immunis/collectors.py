def findings_as_facts(findings, c: Collection) -> None:
    """The scanner's own checks, recorded as third-party findings with tool
    `immunis`, so a consumer treats them like any other tool's until it has
    rules of its own for them."""
    files = c.file_ids()
    for f in findings:
        digest = hashlib.sha256(f"{f.check}|{f.path}|{f.line}|{f.summary}".encode()).hexdigest()[:16]
        fields = dict(tool="immunis", tool_version=__version__, rule_id=f.check, severity=f.severity,
                      message=f.summary, fingerprint=digest)
        if f.path:
            fields["path"] = f.path
        if f.line:
            fields["line"] = f.line
        fid = f"finding:immunis:{digest}"
        c.add("third_party_finding", record(fid, [f.severity], **fields))
        if f.path and f"file:{f.path}" in files:
            c.relate("located_in", fid, f"file:{f.path}")


def scan(root: Path, config, *, project: str, ref: str | None = None, base: str | None = None,
         findings=None, environment: dict | None = None) -> dict:
    """Run every collector and build the artifact."""
    started = _now()
    repo = Repo(root, exclude=getattr(config, "exclude", ()))
    c = Collection()
    ctx: dict = {"base": base}
    for name, fn in COLLECTORS:
        try:
            fn(repo, config, c, ctx)
            c.ran.append(name)
        except Exception as e:  # noqa: BLE001 — a collector failing is a fact about the scan
            c.fail(name, f"{e.__class__.__name__}: {e}"[:200])
    if findings:
        findings_as_facts(findings, c)
    commit = ctx.get("commit") or ref or ""
    subject = {"project": project, "repository": ctx.get("repository", {"forge": "", "owner": "", "name": root.name}),
               "commit": commit, "ref": ref or ""}
    if "change" in ctx:
        subject["change"] = ctx["change"]
    finished = _now()
    return {
        "schema_version": SCHEMA_VERSION,
        "scan": {"id": f"scan:{commit or 'unknown'}:{started}", "sensor": "immunis", "sensor_version": __version__,
                 "started_at": started, "finished_at": finished, "collectors": c.ran, "failed": c.failed,
                 "environment": environment or {}},
        "subject": subject,
        "facts": c.facts,
        "relations": c.relations,
    }
