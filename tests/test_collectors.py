def test_union_mode_through_an_environment_variable_is_a_fact(checkout):
    refs = [r for r in artifact_for(checkout)["facts"]["index_reference"] if r["fields"]["file_path"] == "Dockerfile"]
    env_form = next(r for r in refs if r["fields"]["line"] == 3)
