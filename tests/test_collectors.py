def test_redaction_helpers():
    assert redact_url("https://u:p@h/x") == ("https://<redacted>@h/x", True)
    assert redact_url("https://h/x") == ("https://h/x", False)
    assert "topsecret" not in redact_text("+API_TOKEN=topsecret\n+DEBUG=1\n")
    assert "DEBUG=1" in redact_text("+API_TOKEN=topsecret\n+DEBUG=1\n")


