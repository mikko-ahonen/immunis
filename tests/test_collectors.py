def artifact_for(root, **kw):
    return scan(root, load_config(root), project="widgets", **kw)


def test_artifact_validates_against_the_vendored_schema(checkout):
    jsonschema = pytest.importorskip("jsonschema")
    base = git(checkout, "rev-parse", "HEAD~1").strip()
    art = artifact_for(checkout, base=base)
    jsonschema.validate(art, SCHEMA)
    assert art["scan"]["failed"] == []
    assert set(art["scan"]["collectors"]) == {"repository", "files", "python-deps", "indexes", "workflows", "sops", "env", "suppressions", "local-checks", "diff"}


def test_repository_and_commit(checkout):
    art = artifact_for(checkout)
    repo = art["facts"]["repository"][0]["fields"]
    assert (repo["forge"], repo["owner"], repo["name"]) == ("github", "acme", "widgets")
    assert repo["tracked_only"] is True and repo["file_count"] == 16
    commit = art["facts"]["commit"][0]
    assert commit["id"] == "commit:" + git(checkout, "rev-parse", "HEAD").strip()
    assert commit["fields"]["message_subject"] == "second" and len(commit["fields"]["parents"]) == 1
    assert art["subject"]["commit"] == commit["fields"]["sha"]


def test_files_are_classified_and_digested(checkout):
    files = {f["fields"]["path"]: f for f in artifact_for(checkout)["facts"]["file"]}
    assert files["Dockerfile"]["fields"]["kind"] == "dockerfile"
    assert files["requirements.txt"]["fields"]["kind"] == "requirements"
    assert files[".env"]["fields"]["kind"] == "env"
    assert files[".github/workflows/deploy.yml"]["fields"]["kind"] == "workflow"
    assert files["app/main.py"]["fields"]["kind"] == "python"
    assert "vendored" in files["vendor/lib.py"]["tags"] and "generated" in files["vendor/lib.py"]["tags"]
    assert len(files["app/main.py"]["fields"]["sha256"]) == 64
    assert all("tracked" in f["tags"] for f in files.values())


